#!/usr/bin/env python
"""Generate "thinking + answer" final turns for half of the SFT conversations (distillation).

The SFT conversations are rebuilt exactly as in ``prepare_ranunculus_sft.py``
(same sources, shuffle seed, validation split and identity filter). For a random
half of them, the final assistant turn is regenerated by
``nvidia/Gemma-4-26B-A4B-NVFP4`` with thinking enabled; its reasoning becomes the
``<think>`` block and its answer the new final turn. The other half keep the
human answer and are trained in no-thinking mode. Results are appended to JSONL
so the run can be resumed.

Usage:
    python generate_thinking_sft.py --out artifacts-5/think-data/gen.jsonl \
        --endpoints http://127.0.0.1:18100/v1 http://127.0.0.1:18101/v1
"""

from __future__ import annotations

import argparse
import asyncio
import json
import random
from pathlib import Path

import httpx
from prepare_ranunculus_sft import en_conversations, has_identity, ja_conversations


def build_conversations(seed: int, ja_val_ratio: float) -> list[dict]:
    """Rebuild the SFT conversations with ids, split and language."""
    ja = ja_conversations()
    random.Random(seed).shuffle(ja)
    n_val = int(len(ja) * ja_val_ratio)
    groups = {
        ("ja", "val"): ja[:n_val],
        ("ja", "train"): ja[n_val:],
        ("en", "train"): en_conversations("train"),
        ("en", "val"): en_conversations("validation"),
    }
    out = []
    for (lang, split), convs in groups.items():
        for i, conv in enumerate(convs):
            if not conv or conv[0]["role"] != "user" or conv[-1]["role"] != "assistant" or has_identity(conv):
                continue
            out.append({"id": f"{lang}-{split}-{i}", "lang": lang, "split": split, "messages": conv})
    return out


async def generate(client: httpx.AsyncClient, url: str, history: list[dict], max_tokens: int) -> dict:
    """Generate reasoning and answer for the last user turn of ``history``."""
    body = {
        "model": "gemma4",
        "messages": history,
        "temperature": 0.7,
        "top_p": 0.95,
        "max_tokens": max_tokens,
        "chat_template_kwargs": {"enable_thinking": True},
    }
    for attempt in range(5):
        try:
            r = await client.post(f"{url}/chat/completions", json=body, timeout=1200)
            r.raise_for_status()
            c = r.json()["choices"][0]
            m = c["message"]
            return {"reasoning": (m.get("reasoning") or m.get("reasoning_content") or "").strip(),
                    "answer": (m.get("content") or "").strip(), "finish_reason": c["finish_reason"]}
        except (httpx.HTTPError, KeyError):
            if attempt == 4:
                raise
            await asyncio.sleep(5 * (attempt + 1))
    raise RuntimeError("unreachable")


async def main_async(args) -> None:
    convs = build_conversations(args.seed, args.ja_val_ratio)
    rng = random.Random(args.think_seed)
    selected = [c for c in convs if rng.random() < args.think_ratio]
    if args.limit:
        selected = selected[: args.limit]
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    done = {json.loads(l)["id"] for l in out.open(encoding="utf-8")} if out.exists() else set()
    todo = [c for c in selected if c["id"] not in done]
    print(f"conversations={len(convs)} selected={len(selected)} todo={len(todo)}", flush=True)
    sem = asyncio.Semaphore(args.concurrency)
    lock = asyncio.Lock()
    n = [0]

    async with httpx.AsyncClient() as client:

        async def one(i: int, c: dict) -> None:
            url = args.endpoints[i % len(args.endpoints)]
            async with sem:
                g = await generate(client, url, c["messages"][:-1], args.max_tokens)
            row = {**{k: c[k] for k in ("id", "lang", "split")}, "history": c["messages"][:-1],
                   "human_answer": c["messages"][-1]["content"], **g}
            async with lock:
                with out.open("a", encoding="utf-8") as f:
                    f.write(json.dumps(row, ensure_ascii=False) + "\n")
                n[0] += 1
                if n[0] % 200 == 0:
                    print(f"generated {n[0]}/{len(todo)}", flush=True)

        await asyncio.gather(*(one(i, c) for i, c in enumerate(todo)))
    print(f"finished {n[0]}", flush=True)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--endpoints", nargs="+", required=True)
    ap.add_argument("--think_ratio", type=float, default=0.5)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--think_seed", type=int, default=1)
    ap.add_argument("--ja_val_ratio", type=float, default=0.02)
    ap.add_argument("--max_tokens", type=int, default=6144)
    ap.add_argument("--concurrency", type=int, default=64)
    ap.add_argument("--limit", type=int, default=0)
    asyncio.run(main_async(ap.parse_args()))


if __name__ == "__main__":
    main()

#!/usr/bin/env python
"""Build the SFT v2 dataset (switchable thinking) for Ranunculus-v1-1B.

Conversations are the same as SFT v1 (``generate_thinking_sft.build_conversations``).
Those regenerated by ``generate_thinking_sft.py`` get the teacher's reasoning in a
``<think>`` block and the teacher's answer as the final turn (thinking mode);
all others keep the human answer with an empty ``<think></think>`` block
(no-thinking mode). Loss covers every assistant turn (and the think block of the
final turn) plus ``<|im_end|>``; the empty think block of no-thinking conversations is
excluded (it belongs to the prompt), unless ``--no_mask_empty_think`` is given.

Usage:
    python prepare_ranunculus_sft_v2.py --tokenizer_dir artifacts-0/tokenizer \
        --template artifacts-5/chat_template_v2.jinja --gen artifacts-5/think-data/gen.jsonl \
        --out_dir artifacts-5/sft-v2-data
"""

from __future__ import annotations

import argparse
import json
import random
import re
from collections import Counter
from pathlib import Path

import datasets
from generate_thinking_sft import build_conversations
from prepare_ranunculus_sft import IDENTITY_RE

from transformers import AutoTokenizer

# The teacher may introduce itself; drop such generations as well. Plain "Google" is not matched
# because product names (Google Colab, Google Maps ...) are legitimate content.
TEACHER_RE = re.compile(
    r"gemma|deepmind|(trained|developed|created|built) by google|googleによって(開発|訓練|トレーニング|作成)|google(が|の)(開発した|トレーニングした)(大規模)?言語モデル",
    re.IGNORECASE,
)


EMPTY_THINK = "<think>\n\n</think>\n\n"


def encode(conv: list[dict], tok, mask_empty_think: bool = True, final_turn_only: bool = False) -> dict:
    """Render with the v2 template and label assistant turns.

    The final turn of a thinking conversation is labelled including its think block. With
    ``mask_empty_think`` the empty think block of a no-thinking conversation is left out of the loss.
    With ``final_turn_only`` earlier assistant turns are context only (no loss): the chat template renders
    them without a think block, so training on them teaches "answer right after the assistant header",
    which competes with starting a ``<think>`` block.
    """
    text = tok.apply_chat_template(conv, tokenize=False)
    spans, pos = [], 0
    head = "<|im_start|>assistant\n"
    for i, t in enumerate(conv):
        if t["role"] != "assistant":
            h = f"<|im_start|>{t['role']}\n"
            pos = text.index(h, pos) + len(h) + len(t["content"])
            continue
        start = text.index(head, pos) + len(head)
        if mask_empty_think and i == len(conv) - 1 and t.get("reasoning_content") == "":
            # No-thinking turn: the empty think block is part of the prompt (the chat template adds it when
            # enable_thinking=False), so the model must not learn to emit it itself.
            assert text.startswith(EMPTY_THINK, start)
            start += len(EMPTY_THINK)
        end = text.index(t["content"] + "<|im_end|>", start) + len(t["content"]) + len("<|im_end|>")
        if not final_turn_only or i == len(conv) - 1:
            spans.append((start, end))
        pos = end
    enc = tok(text, return_offsets_mapping=True, add_special_tokens=False)
    labels = [i if any(s <= a < e for s, e in spans) else -100 for i, (a, _) in zip(enc["input_ids"], enc["offset_mapping"])]
    return {"input_ids": enc["input_ids"], "labels": labels}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tokenizer_dir", required=True)
    ap.add_argument("--template", required=True)
    ap.add_argument("--gen", required=True)
    ap.add_argument("--out_dir", required=True)
    ap.add_argument("--max_len", type=int, default=4096)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--no_mask_empty_think", action="store_true", help="v2 (first run) behaviour: train on the empty think block")
    ap.add_argument("--final_turn_only", action="store_true", help="v4: loss only on the final assistant turn")
    args = ap.parse_args()

    tok = AutoTokenizer.from_pretrained(args.tokenizer_dir)
    tok.chat_template = Path(args.template).read_text()
    gen = {r["id"]: r for r in map(json.loads, open(args.gen, encoding="utf-8"))}
    stats = Counter()
    rows = {"train": [], "val": []}
    for c in build_conversations(seed=0, ja_val_ratio=0.02):
        key = f"{c['lang']}/{c['split']}"
        g = gen.get(c["id"])
        if g is not None:
            mode = "think"
            bad = (g["finish_reason"] != "stop" or not g["reasoning"] or not g["answer"]
                   or IDENTITY_RE.search(g["answer"]) or TEACHER_RE.search(g["answer"]))
            if bad:
                stats[f"{key}/think_drop_bad_generation"] += 1
                continue
            conv = c["messages"][:-1] + [{"role": "assistant", "content": g["answer"], "reasoning_content": g["reasoning"]}]
        else:
            mode = "nothink"
            conv = c["messages"][:-1] + [{**c["messages"][-1], "reasoning_content": ""}]
        ex = encode(conv, tok, mask_empty_think=not args.no_mask_empty_think, final_turn_only=args.final_turn_only)
        if len(ex["input_ids"]) > args.max_len:
            stats[f"{key}/{mode}_drop_too_long"] += 1
            continue
        ex.update(lang=c["lang"], mode=mode)
        rows[c["split"]].append(ex)
        stats[f"{key}/{mode}_kept"] += 1
        stats[f"{key}/{mode}_tokens"] += len(ex["input_ids"])
        stats[f"{key}/{mode}_loss_tokens"] += sum(x != -100 for x in ex["labels"])

    # Check what the model is trained to emit right after the assistant header.
    header = tok("<|im_start|>assistant\n", add_special_tokens=False)["input_ids"]
    think_id = tok.convert_tokens_to_ids("<think>")
    for split, r in rows.items():
        for ex in r:
            ids, lab = ex["input_ids"], ex["labels"]
            for j in range(len(ids) - len(header)):
                if ids[j:j + len(header)] == header:
                    k = j + len(header)
                    kind = "masked" if lab[k] == -100 else ("think" if ids[k] == think_id else "direct_text")
                    stats[f"{split}/after_assistant_header/{kind}"] += 1
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for split, r in rows.items():
        random.Random(args.seed).shuffle(r)
        datasets.Dataset.from_list(r).save_to_disk(str(out / split))
    (out / "stats.json").write_text(json.dumps(dict(sorted(stats.items())), indent=2))
    print(json.dumps(dict(sorted(stats.items())), indent=2))
    for mode in ("think", "nothink"):
        ex = next(e for e in rows["train"] if e["mode"] == mode)
        print(f"=== {mode}\n" + tok.decode(ex["input_ids"])[-700:])
        print("--- loss region (head) ---\n" + tok.decode([i for i, l in zip(ex["input_ids"], ex["labels"]) if l != -100])[:300])


if __name__ == "__main__":
    main()
